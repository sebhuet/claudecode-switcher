/**
 * wrapper.ts — renders the `_bin/claudecode-switcher-wrapper.sh` that the official Claude
 * Code extension launches via `claudeCode.claudeProcessWrapper`.
 *
 * The wrapper contains NO routing logic. It calls `_bin/claudecode-switcher-resolve.cjs`
 * (the bundled resolve-cli) via node and exports whatever it prints. Absolute
 * paths are baked in because the setting takes no variable substitution.
 *
 * Handles the three argv shapes the extension uses:
 *   (none)             → launch `claude` from PATH (or the baked fallback)
 *   /path/to/cli.js    → exec node "$@"
 *   /path/to/claude    → exec "$@"
 */
import { execFile } from 'node:child_process';
import * as fs from 'node:fs';
import * as fsp from 'node:fs/promises';
import * as path from 'node:path';
import { promisify } from 'node:util';
import { Paths } from './paths';
import { ClaudeCodeSwitcherError } from './errors';
import { PROVIDER_SETTINGS } from './profiles';
import { chmodQuiet, ensureDir, writeTextAtomic } from './fsx';

const IS_WIN = process.platform === 'win32';
export const WRAPPER_SH = 'claudecode-switcher-wrapper.sh';
/** Windows: the official extension spawns the wrapper without a shell, so it must be a real .exe. */
export const WRAPPER_EXE = 'claudecode-switcher-wrapper.exe';
export const WRAPPER_CS = 'claudecode-switcher-wrapper.cs';
export const WRAPPER_NAME = IS_WIN ? WRAPPER_EXE : WRAPPER_SH;
export const RESOLVE_NAME = 'claudecode-switcher-resolve.cjs';
export const LOG_NAME = 'claudecode-switcher.log';
/** Helper file names from pre-release builds (then called "ccprof"). Recognised and cleaned up, never written. */
export const LEGACY_WRAPPER_NAME = 'ccprof-wrapper.sh';
export const LEGACY_HELPER_NAMES = [LEGACY_WRAPPER_NAME, 'ccprof-resolve.cjs', 'ccprof.log', 'ccprof.log.tmp'];

export interface WrapperOptions {
  version: string;
  /** Absolute path of a node binary, if one was found. */
  nodePath?: string;
  /** Absolute path of an Electron binary usable with ELECTRON_RUN_AS_NODE=1 (VS Code's own). */
  electronPath?: string;
  /** Absolute path of `claude`, used only for the no-argument shape when PATH has none. */
  claudePath?: string;
}

export function sh(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

export function renderWrapperScript(p: Paths, o: WrapperOptions): string {
  const resolveScript = path.join(p.binDir, RESOLVE_NAME);
  const log = path.join(p.binDir, LOG_NAME);
  return `#!/usr/bin/env bash
# ${WRAPPER_NAME} — generated by claudecode-switcher ${o.version}. Do not edit; it is regenerated
# on activation. Configured via the claudeCode.claudeProcessWrapper setting.
#
# The official Claude Code extension runs:  ${WRAPPER_NAME} [<claude binary or cli.js> [args...]]
# This picks the CLAUDE_CONFIG_DIR for the NEW process (via ${RESOLVE_NAME}; routing is
# implemented once, in core/resolve.ts) and execs the real binary untouched. It never logs
# anything in or out. Running sessions on other accounts are never affected.
set -u

ROOT=${sh(p.profilesRoot)}
RESOLVE=${sh(resolveScript)}
LOG=${sh(log)}
NODE_BIN=${sh(o.nodePath ?? '')}
ELECTRON_BIN=${sh(o.electronPath ?? '')}
CLAUDE_FALLBACK=${sh(o.claudePath ?? '')}

log() { printf '%s %s\\n' "$(date '+%Y-%m-%dT%H:%M:%S%z' 2>/dev/null || echo -)" "$*" >> "$LOG" 2>/dev/null || true; }

node_bin() {
  if [ -n "$NODE_BIN" ] && [ -x "$NODE_BIN" ]; then printf '%s' "$NODE_BIN"; return 0; fi
  if command -v node >/dev/null 2>&1; then command -v node; return 0; fi
  return 1
}

run_resolve() {
  local nb
  if nb="$(node_bin)"; then "$nb" "$RESOLVE" --lock; return $?; fi
  if [ -n "$ELECTRON_BIN" ] && [ -x "$ELECTRON_BIN" ]; then ELECTRON_RUN_AS_NODE=1 "$ELECTRON_BIN" "$RESOLVE" --lock; return $?; fi
  echo "claudecode-switcher: no node runtime found; starting on the default account" >&2
  return 2
}

rc=skipped
if [ -n "\${CLAUDE_CONFIG_DIR:-}" ]; then
  rc=explicit   # rule 1: an explicit CLAUDE_CONFIG_DIR outranks routing
elif [ -f "$RESOLVE" ]; then
  export CLAUDECODE_SWITCHER_ROOT="$ROOT" CLAUDECODE_SWITCHER_LOCK_PID=$$
  dir="$(run_resolve)"; rc=$?
  unset CLAUDECODE_SWITCHER_LOCK_PID
  if [ "$rc" -eq 0 ] && [ -n "$dir" ]; then
    export CLAUDE_CONFIG_DIR="$dir"
  fi
  # rc 3 = unknown profile name: resolve already warned on stderr; fall back to default loudly.
fi

# A provider profile (Ollama) carries settings that must outrank the user's settings.json.
PS=""
if [ -n "\${CLAUDE_CONFIG_DIR:-}" ] && [ -f "$CLAUDE_CONFIG_DIR/${PROVIDER_SETTINGS}" ]; then PS="$CLAUDE_CONFIG_DIR/${PROVIDER_SETTINGS}"; fi

# Breadcrumb: paths and profile names only, never tokens.
log "pwd=$PWD config=\${CLAUDE_CONFIG_DIR:-default} provider=\${PS:+yes} rc=$rc argv1=\${1:-<none>}"
if [ -f "$LOG" ] && [ "$(wc -l < "$LOG" 2>/dev/null || echo 0)" -gt 500 ]; then
  tail -n 250 "$LOG" > "$LOG.tmp" 2>/dev/null && mv "$LOG.tmp" "$LOG" 2>/dev/null || true
fi

# Three argv shapes.
if [ "$#" -eq 0 ]; then
  if [ -n "$PS" ]; then set -- --settings "$PS"; fi
  if command -v claude >/dev/null 2>&1; then exec claude "$@"; fi
  if [ -n "$CLAUDE_FALLBACK" ] && [ -x "$CLAUDE_FALLBACK" ]; then exec "$CLAUDE_FALLBACK" "$@"; fi
  echo "claudecode-switcher-wrapper: no arguments and no 'claude' on PATH" >&2
  exit 127
fi
if [ -n "$PS" ]; then set -- "$@" --settings "$PS"; fi
case "$1" in
  *.js|*.cjs|*.mjs)
    if nb="$(node_bin)"; then exec "$nb" "$@"; fi
    if [ -n "$ELECTRON_BIN" ] && [ -x "$ELECTRON_BIN" ]; then ELECTRON_RUN_AS_NODE=1 exec "$ELECTRON_BIN" "$@"; fi
    echo "claudecode-switcher-wrapper: need node to run $1" >&2
    exit 127
    ;;
esac
exec "$@"
`;
}

/** C# verbatim string literal. */
function cs(s: string): string {
  return `@"${s.replace(/"/g, '""')}"`;
}

/**
 * Windows twin of renderWrapperScript, compiled to WRAPPER_EXE by csc. Same contract; the
 * differences come from Windows having no exec: the child is started suspended, put in a
 * kill-on-close job (the extension only ever kills the wrapper's pid), inherits the std
 * handles, and gets the wrapper's command-line tail verbatim (args carry JSON; no re-quoting).
 */
export function renderWrapperCs(p: Paths, o: WrapperOptions): string {
  return `// ${WRAPPER_CS} — generated by claudecode-switcher ${o.version}. Do not edit; it is regenerated
// and compiled to ${WRAPPER_EXE} on activation. See wrapper.ts for the contract.
using System;
using System.Diagnostics;
using System.IO;
using System.Runtime.InteropServices;
using System.Text;

static class Wrapper {
  const string ROOT = ${cs(p.profilesRoot)};
  const string RESOLVE = ${cs(path.join(p.binDir, RESOLVE_NAME))};
  const string LOG = ${cs(path.join(p.binDir, LOG_NAME))};
  const string NODE_BIN = ${cs(o.nodePath ?? '')};
  const string ELECTRON_BIN = ${cs(o.electronPath ?? '')};
  const string CLAUDE_FALLBACK = ${cs(o.claudePath ?? '')};
  const string PROVIDER_SETTINGS = ${cs(PROVIDER_SETTINGS)};

  static int Main(string[] args) {
    string rc = "skipped";
    if (!string.IsNullOrEmpty(Environment.GetEnvironmentVariable("CLAUDE_CONFIG_DIR"))) rc = "explicit";
    else if (File.Exists(RESOLVE)) rc = Resolve();
    // A provider profile (Ollama) carries settings that must outrank the user's settings.json.
    string cfg = Environment.GetEnvironmentVariable("CLAUDE_CONFIG_DIR"), extra = "";
    if (!string.IsNullOrEmpty(cfg) && File.Exists(Path.Combine(cfg, PROVIDER_SETTINGS)))
      extra = " --settings " + Quote(Path.Combine(cfg, PROVIDER_SETTINGS));
    Log("pwd=" + Environment.CurrentDirectory + " config=" + (cfg ?? "default") + " provider=" + (extra.Length > 0 ? "yes" : "") +
        " rc=" + rc + " argv1=" + (args.Length > 0 ? args[0] : "<none>"));

    string app, cmd;
    if (args.Length == 0) {
      app = OnPath("claude.exe") ?? (File.Exists(CLAUDE_FALLBACK) ? CLAUDE_FALLBACK : null);
      if (app == null) { Console.Error.WriteLine("claudecode-switcher-wrapper: no arguments and no claude.exe on PATH"); return 127; }
      cmd = Quote(app);
    } else {
      string tail = Tail(Environment.CommandLine), a = args[0].ToLowerInvariant();
      if (a.EndsWith(".js") || a.EndsWith(".cjs") || a.EndsWith(".mjs")) {
        app = Runtime();
        if (app == null) { Console.Error.WriteLine("claudecode-switcher-wrapper: need node to run " + args[0]); return 127; }
        cmd = Quote(app) + " " + tail;
      } else { app = args[0]; cmd = tail; }
    }
    return Run(app, cmd + extra);
  }

  // node, else VS Code's Electron as node. Sets ELECTRON_RUN_AS_NODE for children when it falls back.
  static string Runtime() {
    if (File.Exists(NODE_BIN)) return NODE_BIN;
    string n = OnPath("node.exe");
    if (n != null) return n;
    if (!File.Exists(ELECTRON_BIN)) return null;
    Environment.SetEnvironmentVariable("ELECTRON_RUN_AS_NODE", "1");
    return ELECTRON_BIN;
  }

  static string Resolve() {
    string rt = Runtime();
    if (rt == null) { Console.Error.WriteLine("claudecode-switcher: no node runtime found; starting on the default account"); return "2"; }
    var psi = new ProcessStartInfo(rt, Quote(RESOLVE) + " --lock --cwd " + Quote(Environment.CurrentDirectory));
    psi.UseShellExecute = false; psi.CreateNoWindow = true; psi.RedirectStandardOutput = true;
    psi.StandardOutputEncoding = Encoding.UTF8;
    psi.EnvironmentVariables["CLAUDECODE_SWITCHER_ROOT"] = ROOT;
    psi.EnvironmentVariables["CLAUDECODE_SWITCHER_LOCK_PID"] = Process.GetCurrentProcess().Id.ToString();
    Environment.SetEnvironmentVariable("ELECTRON_RUN_AS_NODE", null); // never leak it to claude
    try {
      using (var p = Process.Start(psi)) {
        string dir = p.StandardOutput.ReadToEnd().Trim();
        p.WaitForExit();
        if (p.ExitCode == 0 && dir.Length > 0) Environment.SetEnvironmentVariable("CLAUDE_CONFIG_DIR", dir);
        return p.ExitCode.ToString();
      }
    } catch (Exception e) { Console.Error.WriteLine("claudecode-switcher: " + e.Message); return "1"; }
  }

  static string OnPath(string exe) {
    foreach (string d in (Environment.GetEnvironmentVariable("PATH") ?? "").Split(';')) {
      string dir = d.Trim().Trim('"');
      if (dir.Length == 0) continue;
      try { string f = Path.Combine(dir, exe); if (File.Exists(f)) return f; } catch (ArgumentException) { }
    }
    return null;
  }

  // Everything after argv[0], exactly as received.
  static string Tail(string c) {
    int i = 0;
    if (c.StartsWith("\\"")) { i = c.IndexOf('"', 1); i = i < 0 ? c.Length : i + 1; }
    else while (i < c.Length && c[i] != ' ' && c[i] != '\\t') i++;
    return c.Substring(i).TrimStart(' ', '\\t');
  }

  static string Quote(string s) {
    if (s.Length > 0 && s.IndexOfAny(new[] { ' ', '\\t', '"' }) < 0) return s;
    var sb = new StringBuilder("\\""); int bs = 0;
    foreach (char ch in s) {
      if (ch == '\\\\') { bs++; continue; }
      sb.Append('\\\\', ch == '"' ? bs * 2 + 1 : bs).Append(ch); bs = 0;
    }
    return sb.Append('\\\\', bs * 2).Append('"').ToString();
  }

  static void Log(string line) {
    try {
      File.AppendAllText(LOG, DateTime.Now.ToString("yyyy-MM-ddTHH:mm:sszzz") + " " + line + Environment.NewLine);
      string[] all = File.ReadAllLines(LOG);
      if (all.Length > 500) File.WriteAllLines(LOG, new ArraySegment<string>(all, all.Length - 250, 250));
    } catch { }
  }

  static int Run(string app, string cmd) {
    var si = new STARTUPINFO();
    si.cb = Marshal.SizeOf(si);
    si.dwFlags = 0x100; // STARTF_USESTDHANDLES
    si.hStdInput = Std(-10); si.hStdOutput = Std(-11); si.hStdError = Std(-12);
    PROCESS_INFORMATION pi;
    if (!CreateProcessW(app, new StringBuilder(cmd), IntPtr.Zero, IntPtr.Zero, true, 0x4 /* CREATE_SUSPENDED */, IntPtr.Zero, null, ref si, out pi)) {
      Console.Error.WriteLine("claudecode-switcher-wrapper: cannot start " + app + " (error " + Marshal.GetLastWin32Error() + ")");
      return 127;
    }
    IntPtr job = CreateJobObjectW(IntPtr.Zero, null);
    var lim = new JOBOBJECT_EXTENDED_LIMIT_INFORMATION();
    // KILL_ON_JOB_CLOSE | SILENT_BREAKAWAY_OK: claude.exe dies with the wrapper, but what it
    // starts itself (daemon, background jobs) lives on, as without a wrapper.
    lim.Basic.LimitFlags = 0x2000 | 0x1000;
    if (job == IntPtr.Zero || !SetInformationJobObject(job, 9, ref lim, (uint)Marshal.SizeOf(lim)) || !AssignProcessToJobObject(job, pi.hProcess))
      Log("warning: no kill-on-close job (error " + Marshal.GetLastWin32Error() + "); the child may outlive the wrapper");
    ResumeThread(pi.hThread);
    WaitForSingleObject(pi.hProcess, 0xFFFFFFFF);
    uint code;
    GetExitCodeProcess(pi.hProcess, out code);
    return (int)code;
  }

  static IntPtr Std(int which) {
    IntPtr h = GetStdHandle(which);
    SetHandleInformation(h, 1, 1); // HANDLE_FLAG_INHERIT
    return h;
  }

  [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
  struct STARTUPINFO {
    public int cb; public string lpReserved, lpDesktop, lpTitle;
    public int dwX, dwY, dwXSize, dwYSize, dwXCountChars, dwYCountChars, dwFillAttribute, dwFlags;
    public short wShowWindow, cbReserved2; public IntPtr lpReserved2, hStdInput, hStdOutput, hStdError;
  }
  struct PROCESS_INFORMATION { public IntPtr hProcess, hThread; public int dwProcessId, dwThreadId; }
  struct JOBOBJECT_BASIC_LIMIT_INFORMATION {
    public long PerProcessUserTimeLimit, PerJobUserTimeLimit; public uint LimitFlags;
    public UIntPtr MinimumWorkingSetSize, MaximumWorkingSetSize; public uint ActiveProcessLimit;
    public UIntPtr Affinity; public uint PriorityClass, SchedulingClass;
  }
  struct IO_COUNTERS { public ulong a, b, c, d, e, f; }
  struct JOBOBJECT_EXTENDED_LIMIT_INFORMATION {
    public JOBOBJECT_BASIC_LIMIT_INFORMATION Basic; public IO_COUNTERS Io;
    public UIntPtr ProcessMemoryLimit, JobMemoryLimit, PeakProcessMemoryUsed, PeakJobMemoryUsed;
  }
  [DllImport("kernel32.dll", SetLastError = true, CharSet = CharSet.Unicode)]
  static extern bool CreateProcessW(string app, StringBuilder cmd, IntPtr pa, IntPtr ta, bool inherit, uint flags, IntPtr env, string cwd, ref STARTUPINFO si, out PROCESS_INFORMATION pi);
  [DllImport("kernel32.dll", SetLastError = true, CharSet = CharSet.Unicode)] static extern IntPtr CreateJobObjectW(IntPtr attrs, string name);
  [DllImport("kernel32.dll", SetLastError = true)] static extern bool SetInformationJobObject(IntPtr job, int cls, ref JOBOBJECT_EXTENDED_LIMIT_INFORMATION info, uint len);
  [DllImport("kernel32.dll", SetLastError = true)] static extern bool AssignProcessToJobObject(IntPtr job, IntPtr proc);
  [DllImport("kernel32.dll")] static extern uint ResumeThread(IntPtr thread);
  [DllImport("kernel32.dll")] static extern uint WaitForSingleObject(IntPtr h, uint ms);
  [DllImport("kernel32.dll")] static extern bool GetExitCodeProcess(IntPtr h, out uint code);
  [DllImport("kernel32.dll")] static extern IntPtr GetStdHandle(int which);
  [DllImport("kernel32.dll")] static extern bool SetHandleInformation(IntPtr h, uint mask, uint flags);
}
`;
}

/** csc.exe from .NET Framework 4, which every Windows 10/11 ships. */
function findCsc(): string {
  const fw = path.join(process.env.WINDIR ?? 'C:\\Windows', 'Microsoft.NET');
  for (const dir of ['Framework64', 'Framework']) {
    const csc = path.join(fw, dir, 'v4.0.30319', 'csc.exe');
    if (fs.existsSync(csc)) return csc;
  }
  throw new ClaudeCodeSwitcherError('NO_CSC', `The Windows wrapper is compiled with the .NET Framework 4 csc.exe, not found under ${fw}.`);
}

/** A running exe cannot be overwritten or deleted, only renamed: move it aside, then put the new one in. */
async function replaceExe(tmp: string, dest: string): Promise<void> {
  try {
    await fsp.rm(dest, { force: true });
  } catch {
    await fsp.rename(dest, `${dest}.old-${Date.now()}`);
  }
  await fsp.rename(tmp, dest);
}

async function materializeExe(p: Paths, o: WrapperOptions): Promise<boolean> {
  const src = path.join(p.binDir, WRAPPER_CS);
  const exe = path.join(p.binDir, WRAPPER_EXE);
  for (const f of await fsp.readdir(p.binDir)) {
    if (f.startsWith(`${WRAPPER_EXE}.old-`)) await fsp.rm(path.join(p.binDir, f), { force: true }).catch(() => undefined);
  }
  const code = renderWrapperCs(p, o);
  if ((await readOrEmpty(src)) === code && fs.existsSync(exe)) return false;
  await writeTextAtomic(src, code, 0o644);
  const tmp = `${exe}.${process.pid}.tmp.exe`;
  try {
    await promisify(execFile)(findCsc(), ['/nologo', '/target:exe', '/optimize+', `/out:${tmp}`, src], { windowsHide: true });
  } catch (e) {
    await fsp.rm(src, { force: true }); // force a retry next time
    const out = (e as { stdout?: string }).stdout?.trim();
    throw new ClaudeCodeSwitcherError('WRAPPER_COMPILE', `Compiling ${WRAPPER_CS} failed: ${out || (e as Error).message}`);
  }
  await replaceExe(tmp, exe);
  return true;
}

export interface MaterializeInput extends WrapperOptions {
  /** Contents of the bundled resolve-cli (claudecode-switcher-resolve.cjs). */
  resolveScriptSource: string;
}

export interface MaterializeResult {
  wrapperPath: string;
  resolvePath: string;
  changed: boolean;
}

/** Write (or refresh) the helper scripts under `_bin/`. Idempotent; only rewrites on change. */
export async function materializeHelpers(p: Paths, input: MaterializeInput): Promise<MaterializeResult> {
  await ensureDir(p.profilesRoot, 0o700);
  await chmodQuiet(p.profilesRoot, 0o700);
  await ensureDir(p.binDir, 0o755);
  const wrapperPath = path.join(p.binDir, WRAPPER_NAME);
  const resolvePath = path.join(p.binDir, RESOLVE_NAME);
  let changed = false;
  if (IS_WIN) {
    changed = await materializeExe(p, input);
  } else {
    const wrapper = renderWrapperScript(p, input);
    if ((await readOrEmpty(wrapperPath)) !== wrapper) {
      await writeTextAtomic(wrapperPath, wrapper, 0o755);
      changed = true;
    }
  }
  if ((await readOrEmpty(resolvePath)) !== input.resolveScriptSource) {
    await writeTextAtomic(resolvePath, input.resolveScriptSource, 0o644);
    changed = true;
  }
  return { wrapperPath, resolvePath, changed };
}

/** Remove everything claudecode-switcher put under `_bin/`. Profiles and the map are untouched. */
export async function removeHelpers(p: Paths): Promise<string[]> {
  const removed: string[] = [];
  let present: string[] = [];
  try {
    present = await fsp.readdir(p.binDir);
  } catch {
    /* absent */
  }
  const ours = [WRAPPER_SH, WRAPPER_EXE, WRAPPER_CS, RESOLVE_NAME, LOG_NAME, `${LOG_NAME}.tmp`, ...LEGACY_HELPER_NAMES];
  for (const f of present.filter((f) => ours.includes(f) || f.startsWith(`${WRAPPER_EXE}.old-`))) {
    const fp = path.join(p.binDir, f);
    try {
      await fsp.rm(fp);
      removed.push(fp);
    } catch {
      /* a running wrapper.exe stays locked until its conversation ends */
    }
  }
  try {
    if ((await fsp.readdir(p.binDir)).length === 0) await fsp.rmdir(p.binDir);
  } catch {
    /* shared with another tool or absent */
  }
  try {
    await fsp.rm(p.locksDir, { recursive: true, force: true });
  } catch {
    /* absent */
  }
  return removed;
}

async function readOrEmpty(f: string): Promise<string> {
  try {
    return await fsp.readFile(f, 'utf8');
  } catch {
    return '';
  }
}
